/**
 * Traduzione di una voce di dettaglio. `key` è la chiave del cubo ("IF045" per la coesione,
 * "FONDO:dicitura" per gli altri fondi); restituisce undefined se la voce non è ancora tradotta.
 */
export function translateCategory(key: string, sourceLabel: string): string | undefined {
  if (key.startsWith('IF')) return INTERVENTION_FIELDS[key.slice(2)];
  const technical = /^TA\.[\d()]+\.\d+\s+(.*)$/.exec(sourceLabel);
  return technical ? TECHNICAL_ASSISTANCE[technical[1]] : OTHER_FUND_LABELS[sourceLabel];
}
